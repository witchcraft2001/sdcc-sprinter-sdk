static u8 sprite24[24 * 24];

static void make_sprite24(void) {
    u16 i;
    u8 x, y;

    for (i = 0; i < sizeof(sprite24); i++) sprite24[i] = GFX_TRANSPARENT_COLOR;
    for (y = 0; y < 24; y++) {
        for (x = 0; x < 24; x++) {
            if (x == 0 || y == 0 || x == 23 || y == 23 || x == y || x == (23 - y))
                sprite24[(u16)y * 24 + x] = 2 + ((x + y) & 7);
        }
    }
}

static void clear_screens(void) {
    volatile u8 *vram = (volatile u8 *)0xC000;
    u8 y;

    video_mapvram(3, VRAM_PAGE_BASE);
    y = 0;
    do {
        outp(PORT_PAL_ADDR, y);
        memset((void *)vram, y & 1, 320);
        memset((void *)(vram + 320), y & 1, 320);
        y++;
    } while (y != 0);
    video_safe_porty();
}

static void show_screen0(void) {
    if (gfx_get_active_screen() != GFX_SCREEN_0)
        gfx_flip();
}

static void draw_primitives(void) {
    gfx_draw_rect(GFX_SCREEN_0, 12, 18, 296, 220, 15, GFX_OPAQUE);
    gfx_fill_rect(GFX_SCREEN_0, 20, 204, 80, 22, 1, GFX_OPAQUE);
    gfx_draw_line(GFX_SCREEN_0, 18, 198, 104, 226, 8, GFX_OPAQUE);
    gfx_draw_line_thick(GFX_SCREEN_0, 24, 226, 300, 34, 3, 4, GFX_OPAQUE);
    gfx_draw_circle(GFX_SCREEN_0, 260, 190, 24, 14, GFX_OPAQUE);
}

void main(void) {
    video_setmode(VMODE_320);
    show_screen0();
    video_setpal_range(0, sizeof(demo_palette) / sizeof(demo_palette[0]), demo_palette);
    make_sprite24();
    clear_screens();
    draw_primitives();

    gfx_draw_sprite8(GFX_SCREEN_0, 24, 30, sprite8, GFX_MASKED);
    gfx_draw_sprite16(GFX_SCREEN_0, 64, 60, sprite16, GFX_MASKED);
    gfx_draw_sprite24(GFX_SCREEN_0, 120, 90, sprite24, GFX_MASKED);

    gfx_draw_sprite16(GFX_SCREEN_0, 180, 80, sprite16, GFX_MASKED | GFX_VRAM_ONLY);
    dss_waitkey();
    gfx_restore_sprite16(GFX_SCREEN_0, 180, 80);

    dss_waitkey();
    video_setmode(VMODE_TEXT80);
}
