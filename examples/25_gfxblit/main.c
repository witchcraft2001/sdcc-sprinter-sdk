static void show_screen0(void) {
    if (gfx_get_active_screen() != GFX_SCREEN_0)
        gfx_flip();
}

static void clear_screens(void) {
    volatile u8 *vram = (volatile u8 *)0xC000;
    u8 y;

    video_mapvram(3, VRAM_PAGE_BASE);
    y = 0;
    do {
        outp(PORT_PAL_ADDR, y);
        memset((void *)vram, 0, 320);
        memset((void *)(vram + 320), 0, 320);
        y++;
    } while (y != 0);
    video_safe_porty();
}

static void draw_source_block(u8 screen, u16 x, u8 y) {
    u8 i;

    gfx_draw_rect(screen, x, y, 96, 56, 15, GFX_OPAQUE);
    for (i = 0; i < 7; i++) {
        gfx_fill_rect(screen, x + 2, y + 2 + ((u16)i * 7), 92, 6,
                      3 + (i & 7), GFX_OPAQUE);
    }
    gfx_draw_line(screen, x + 4, y + 4, x + 88, y + 48, 15, GFX_OPAQUE);
    gfx_draw_line(screen, x + 88, y + 4, x + 4, y + 48, 8, GFX_OPAQUE);
}

static void draw_scroll_block(u8 screen, u16 x, u8 y) {
    u8 i;

    gfx_draw_rect(screen, x, y, 112, 72, 15, GFX_OPAQUE);
    gfx_fill_rect(screen, x + 1, y + 1, 110, 70, 1, GFX_OPAQUE);
    for (i = 0; i < 10; i++) {
        gfx_fill_rect(screen, x + 6 + ((u16)i * 10), y + 8, 5, 56,
                      4 + (i & 3), GFX_OPAQUE);
    }
    for (i = 0; i < 8; i++) {
        gfx_draw_hline(screen, x + 4, y + 6 + ((u16)i * 8), 104,
                       7 + (i & 1), GFX_OPAQUE);
    }
}

static void draw_scene(void) {
    gfx_fill_rect(GFX_SCREEN_0, 0, 0, 320, 0, 0, GFX_OPAQUE);
    gfx_fill_rect(GFX_SCREEN_1, 0, 0, 320, 0, 0, GFX_OPAQUE);

    gfx_draw_rect(GFX_SCREEN_0, 8, 8, 304, 240, 15, GFX_OPAQUE);
    gfx_draw_hline(GFX_SCREEN_0, 16, 82, 288, 13, GFX_OPAQUE);
    gfx_draw_hline(GFX_SCREEN_0, 16, 170, 288, 13, GFX_OPAQUE);

    draw_source_block(GFX_SCREEN_0, 20, 20);
    gfx_draw_rect(GFX_SCREEN_0, 172, 20, 96, 56, 12, GFX_OPAQUE);
    gfx_blit_rect(GFX_SCREEN_0, 172, 20, GFX_SCREEN_0, 20, 20, 96, 56);

    draw_scroll_block(GFX_SCREEN_0, 40, 96);
    gfx_scroll_rect(GFX_SCREEN_0, 40, 104, 40, 96, 112, 64);
    gfx_fill_rect(GFX_SCREEN_0, 41, 97, 110, 7, 11, GFX_OPAQUE);

    gfx_copy_rect(GFX_SCREEN_1, GFX_SCREEN_0, 20, 20, 96, 56);
    gfx_blit_rect(GFX_SCREEN_1, 180, 104, GFX_SCREEN_0, 40, 96, 112, 72);

    gfx_draw_rect(GFX_SCREEN_0, 176, 96, 96, 56, 14, GFX_OPAQUE);
    gfx_draw_sprite16(GFX_SCREEN_0, 216, 116, sprite16, GFX_MASKED | GFX_VRAM_ONLY);
}

void main(void) {
    video_setmode(VMODE_320);
    show_screen0();
    video_setpal_range(0, sizeof(palette) / sizeof(palette[0]), palette);
    clear_screens();
    draw_scene();

    dss_waitkey();
    gfx_restore_rect(GFX_SCREEN_0, 216, 116, 16, 16);

    dss_waitkey();
    if (gfx_get_active_screen() != GFX_SCREEN_1)
        gfx_flip();

    dss_waitkey();
    video_setmode(VMODE_TEXT80);
}
